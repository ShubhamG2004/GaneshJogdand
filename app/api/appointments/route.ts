
import { NextResponse } from "next/server";
import nodemailer from "nodemailer";
import { getFirebaseDb } from "@/lib/firebase-admin";

export async function POST(request: Request) {
  try {
    // Get form data
    const body = await request.json();

    const { name, email, phone, service, message } = body;

    // Validate required fields
    if (
      typeof name !== "string" ||
      typeof email !== "string" ||
      typeof phone !== "string" ||
      typeof service !== "string" ||
      typeof message !== "string" ||
      !name.trim() ||
      !email.trim() ||
      !phone.trim() ||
      !service.trim() ||
      !message.trim()
    ) {
      return NextResponse.json(
        { error: "Please fill in all required fields." },
        { status: 400 }
      );
    }

    const patientEmail = email.trim();

    // Validate email
    if (
      patientEmail.length > 254 ||
      !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(patientEmail) ||
      name.length > 100 ||
      phone.length > 30 ||
      service.length > 100 ||
      message.length > 3000
    ) {
      return NextResponse.json(
        { error: "Please enter valid appointment details." },
        { status: 400 }
      );
    }

    // Create appointment object
    const appointment = {
      id: crypto.randomUUID(),
      createdAt: new Date().toISOString(),
      status: "new",
      name: name.trim(),
      email: patientEmail,
      phone: phone.trim(),
      service: service.trim(),
      message: message.trim(),
    };

    // Save to Firebase
    try {
      await getFirebaseDb()
        .collection("appointments")
        .doc(appointment.id)
        .set(appointment);

    } catch (error) {
      console.error("Firebase error:", error);

      return NextResponse.json(
        { error: "Unable to save appointment." },
        { status: 503 }
      );
    }

    // SMTP configuration
    const smtpHost = process.env.SMTP_HOST;
    const smtpPort = Number(process.env.SMTP_PORT || 587);
    const smtpUser = process.env.SMTP_USER;
    const smtpPassword = process.env.SMTP_PASSWORD;
    const doctorEmail = process.env.DOCTOR_EMAIL;

    if (
      !smtpHost ||
      !smtpUser ||
      !smtpPassword ||
      !doctorEmail
    ) {
      return NextResponse.json(
        {
          error: "Appointment saved, but email configuration is missing.",
        },
        { status: 503 }
      );
    }

    // Create SMTP transporter
    const transporter = nodemailer.createTransport({
      host: smtpHost,
      port: smtpPort,
      secure: smtpPort === 465,
      auth: {
        user: smtpUser,
        pass: smtpPassword,
      },
    });

    // Send appointment email
    try {
      await transporter.sendMail({
        from: {
          name: "Clinic Appointment",
          address: smtpUser,
        },

        to: doctorEmail,

        // Doctor can reply directly to the patient's email
        replyTo: {
          name: appointment.name,
          address: appointment.email,
        },

        subject: `New Appointment Request - ${appointment.name}`,

        text: `
NEW APPOINTMENT REQUEST

Patient Details:

Name: ${appointment.name}
Email: ${appointment.email}
Phone: ${appointment.phone}

Requested Service:
${appointment.service}

Patient Message:
${appointment.message}

Appointment ID: ${appointment.id}
Submitted At: ${appointment.createdAt}
        `,

        html: `
          <div style="font-family: Arial, sans-serif; padding: 20px; color: #333;">

            <h2 style="color: #2563eb;">
              New Appointment Request
            </h2>

            <hr />

            <h3>Patient Details</h3>

            <p><strong>Name:</strong> ${escapeHtml(appointment.name)}</p>

            <p><strong>Email:</strong> ${escapeHtml(appointment.email)}</p>

            <p><strong>Phone:</strong> ${escapeHtml(appointment.phone)}</p>

            <p><strong>Service:</strong> ${escapeHtml(appointment.service)}</p>

            <h3>Patient Message</h3>

            <p>${escapeHtml(appointment.message).replace(/\n/g, "<br>")}</p>

            <hr />

            <p><strong>Appointment ID:</strong> ${appointment.id}</p>

            <p><strong>Submitted At:</strong> ${appointment.createdAt}</p>

            <p style="color: #64748b; font-size: 12px;">
              This email was automatically generated by the clinic appointment system.
            </p>

          </div>
        `,
      });

    } catch (error) {
      console.error("Email sending error:", error);

      return NextResponse.json(
        {
          error: "Appointment saved, but doctor email could not be sent. Please contact the clinic.",
        },
        { status: 502 }
      );
    }

    // Success response
    return NextResponse.json(
      {
        success: true,
        message: "Appointment request submitted successfully!",
        appointment,
      },
      { status: 201 }
    );

  } catch (error) {
    console.error("Appointment API error:", error);

    return NextResponse.json(
      { error: "Something went wrong. Please try again." },
      { status: 500 }
    );
  }
}

// Escape HTML to prevent HTML injection in emails
function escapeHtml(value: string) {
  return value.replace(/[&<>"']/g, (char) => {
    const entities: Record<string, string> = {
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#39;",
    };

    return entities[char];
  });
}
